/* ---- THE WALL, GENERATED ---------------------------------------------------
   Typed by hand this would be 75 near-identical literals and one of them would be
   out of order within a week. Generated, the ordering is a property of the loop and
   check D asserts it anyway. */
export const WALL_YEAR_FIRST = 1951;
export const WALL_YEAR_LAST  = 2025;   // the only invented number in this file
export const WALL_X0 = 0.035, WALL_X1 = 0.965, WALL_Z = 0.135;

const wallStations = {};
const chrysalisWallRun = [];
for (let y = WALL_YEAR_FIRST; y <= WALL_YEAR_LAST; y++){
  const t = (y - WALL_YEAR_FIRST) / (WALL_YEAR_LAST - WALL_YEAR_FIRST);
  const name = `wall_${y}`;
  wallStations[name] = { x: WALL_X0 + (WALL_X1 - WALL_X0) * t, z: WALL_Z };
  chrysalisWallRun.push(name);
}
export { chrysalisWallRun };

