/* ============================================================================
   BLOCKING. Six of the eleven. BF-33, BF-35 and BF-38 are DISSOLVE and TRANSFER on
   a beam and a wall — no body crosses ground in them and MOVES tables would be
   invented motion. BF-34 is blocked precisely BECAUSE nobody moves in it: its whole
   content is that Mara does not turn, and an occupancy that holds her at
   mara_pool_north through a unit whose only line is "Do not turn around" is the
   handoff doing real work.
   ============================================================================ */
const carryOver = (occ, ...who) =>
  Object.fromEntries(Object.entries(occ).filter(([k]) => who.includes(k)));

